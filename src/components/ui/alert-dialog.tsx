"use client"

import * as React from "react"
import { cn } from "@/lib/utils"
import { Dialog as AlertDialogPrimitive } from "radix-ui"

import { Button } from "@/components/ui/button"

/**
 * Confirmation dialogs. Built on Radix `Dialog` (not `AlertDialog`) on purpose: Radix's own alert dialog ignores a tap on the dim area
 * around it, but on a phone people expect that tap (and Esc) to dismiss, the same as the Back button. The role stays `alertdialog`.
 * While an action is running its Cancel button is disabled, and then the dim area and Esc do nothing either, so a save cannot be
 * walked away from by accident. Every dialog in the app goes through this file, so the behaviour is the same everywhere.
 */
function AlertDialog({
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Root>) {
  return <AlertDialogPrimitive.Root data-slot="alert-dialog" {...props} />
}

function AlertDialogTrigger({
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Trigger>) {
  return (
    <AlertDialogPrimitive.Trigger data-slot="alert-dialog-trigger" {...props} />
  )
}

function AlertDialogPortal({
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Portal>) {
  return (
    <AlertDialogPrimitive.Portal data-slot="alert-dialog-portal" {...props} />
  )
}

function AlertDialogOverlay({
  className,
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Overlay>) {
  return (
    <AlertDialogPrimitive.Overlay
      data-slot="alert-dialog-overlay"
      className={cn(
        "fixed inset-0 z-50 bg-black/50 duration-100 supports-backdrop-filter:backdrop-blur-xs data-open:animate-in data-open:fade-in-0 data-closed:animate-out data-closed:fade-out-0",
        className
      )}
      {...props}
    />
  )
}

function AlertDialogContent({
  className,
  size = "default",
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Content> & {
  size?: "default" | "sm"
}) {
  const ref = React.useRef<HTMLDivElement>(null)
  // A running action disables Cancel: that is the signal not to let a tap outside or Esc close the dialog.
  const busy = () => ref.current?.querySelector('[data-slot="alert-dialog-cancel"]:disabled') != null
  return (
    <AlertDialogPortal>
      <AlertDialogOverlay />
      <AlertDialogPrimitive.Content
        ref={ref}
        role="alertdialog"
        data-slot="alert-dialog-content"
        data-size={size}
        onPointerDownOutside={(event) => {
          if (busy()) event.preventDefault()
        }}
        onInteractOutside={(event) => {
          if (busy()) event.preventDefault()
        }}
        onEscapeKeyDown={(event) => {
          if (busy()) event.preventDefault()
        }}
        className={cn(
          "group/alert-dialog-content fixed top-1/2 left-1/2 z-50 grid max-h-[85dvh] w-[calc(100%-2*var(--spacing-inset))] -translate-x-1/2 -translate-y-1/2 gap-group overflow-y-auto rounded-xl bg-popover p-inset text-popover-foreground ring-1 ring-foreground/10 duration-100 outline-none data-[size=default]:max-w-form data-[size=sm]:max-w-hint data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
          className
        )}
        {...props}
      />
    </AlertDialogPortal>
  )
}

function AlertDialogHeader({
  className,
  ...props
}: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="alert-dialog-header"
      className={cn(
        "grid grid-rows-[auto_1fr] place-items-center gap-stack text-center has-data-[slot=alert-dialog-media]:grid-rows-[auto_auto_1fr] has-data-[slot=alert-dialog-media]:gap-x-group sm:group-data-[size=default]/alert-dialog-content:place-items-start sm:group-data-[size=default]/alert-dialog-content:text-left sm:group-data-[size=default]/alert-dialog-content:has-data-[slot=alert-dialog-media]:grid-rows-[auto_1fr]",
        className
      )}
      {...props}
    />
  )
}

function AlertDialogFooter({
  className,
  ...props
}: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="alert-dialog-footer"
      className={cn(
        "-mx-inset -mb-inset flex flex-col-reverse gap-stack rounded-b-xl border-t bg-muted/50 p-inset group-data-[size=sm]/alert-dialog-content:grid group-data-[size=sm]/alert-dialog-content:grid-cols-2 sm:flex-row sm:justify-end",
        className
      )}
      {...props}
    />
  )
}

