/**
 * Compiles SeatMate's Tailwind + custom design-token merge tables once at build/dev time into
 * `src/lib/cn-tables.mjs` so client bundles only ship the tiny `cn/engine` runtime + compiled tables
 * (~25 KB raw) instead of `cn/config`'s full runtime compiler (~159 KB raw).
 *
 * Run via `npm run cn:build` whenever tokens in `src/lib/cn-tokens.ts` change.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { compileToSource, mergeConfigs } from "cn/compiler";
import { defaultConfig } from "cn/config";
import { CN_CONFIG_EXTENSION } from "../src/lib/cn-tokens";

const merged = mergeConfigs(defaultConfig(), CN_CONFIG_EXTENSION);
const source = compileToSource(merged);
const banner = `/* eslint-disable */\n// AUTO-GENERATED by scripts/generate-cn-tables.ts — do not edit manually.\n`;
const outPath = join(process.cwd(), "src", "lib", "cn-tables.mjs");
writeFileSync(outPath, `${banner}${source}`, "utf8");
console.log(`Generated ${outPath} (${source.length} B)`);
